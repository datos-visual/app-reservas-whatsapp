create table if not exists public.missed_calls (
  id                        bigint generated by default as identity primary key,
  store_id                  uuid not null references public.stores (id) on delete cascade,
  caller_phone              text,
  is_anonymous              boolean not null default false,
  did_e164                  text not null,
  provider                  text not null default 'twilio',
  provider_call_id          text,
  occurred_at               timestamptz not null default now(),
  status                    text not null default 'pending'
                              check (status in ('pending', 'sent', 'skipped')),
  skip_reason               text
                              check (skip_reason is null or skip_reason in
                                ('quota_exceeded', 'optout', 'anonymous', 'disabled',
                                 'template_not_approved', 'dedupe_24h', 'no_whatsapp_account')),
  template_sent_at          timestamptz,
  wa_message_id             text,
  callback_requested        boolean not null default false,
  resulted_in_conversation  boolean not null default false,
  resulted_in_booking_id    bigint references public.appointments (id) on delete set null,
  created_at                timestamptz not null default now()
);
-- CRÍTICO — idempotencia del webhook de voz (Twilio reintenta CallSid)
create unique index if not exists missed_calls_provider_call_unique
  on public.missed_calls (provider, provider_call_id)
  where provider_call_id is not null;
create index if not exists missed_calls_pending_idx
  on public.missed_calls (store_id, occurred_at)
  where status = 'pending';
create index if not exists missed_calls_store_occurred_idx
  on public.missed_calls (store_id, occurred_at desc);

-- CRÍTICO — dedupe 1 plantilla/(tienda,teléfono)/día natural local (patrón 23505)

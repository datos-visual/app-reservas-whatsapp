-- =====================================================================
-- SCHEMA CONSOLIDADO — CanalAgenda (SaaS reservas por WhatsApp)
-- =====================================================================
-- FUENTE DE VERDAD para recrear la base de datos desde cero.
-- Generado a partir de la foto REAL del Supabase de producción
-- (information_schema + pg_indexes + pg_constraint, julio 2026),
-- NO desde el schema.sql antiguo (desactualizado, no usar).
--
-- Idempotente: se puede ejecutar sobre una BD vacía o ya existente.
-- Uso: Supabase SQL Editor de un proyecto nuevo → pegar y ejecutar.
--
-- Reglas que este esquema garantiza (NO tocar sin entender el porqué):
--   * Idempotencia de mensajes: unique parcial (store_id, message_id)
--   * Anti doble-reserva: unique parcial (store_id, start_at) WHERE confirmed
--   * Multi-tenant: todas las tablas hijas cuelgan de stores.id (store_id)
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) STORES — tenant / tienda
-- ---------------------------------------------------------------------
create table if not exists public.stores (
  id                            uuid primary key default gen_random_uuid(),
  name                          text not null,
  timezone                      text not null default 'Europe/Madrid',
  appointment_duration_minutes  integer not null default 30,
  business_email                text,
  business_phone                text,
  created_at                    timestamptz not null default now()
);
-- El estado del onboarding (draft/ready) NO se guarda: se deriva de las conexiones.

-- ---------------------------------------------------------------------
-- 2) WHATSAPP_ACCOUNTS — mapeo phone_number_id → store_id + credenciales
-- ---------------------------------------------------------------------
create table if not exists public.whatsapp_accounts (
  id               uuid primary key default gen_random_uuid(),
  store_id         uuid not null references public.stores (id) on delete cascade,
  phone_number_id  text not null,
  waba_id          text,
  access_token     text not null,
  verify_token     text not null,
  is_active        boolean not null default true,
  token_expires_at timestamptz,  -- null = token permanente (paso 6)
  created_at       timestamptz not null default now()
);

-- Unicidad global de phone_number_id (un número solo puede pertenecer a una fila)
create unique index if not exists whatsapp_accounts_phone_number_id_key
  on public.whatsapp_accounts (phone_number_id);

-- Un solo whatsapp_account por tienda
create unique index if not exists whatsapp_accounts_store_id_key
  on public.whatsapp_accounts (store_id);

-- Variantes parciales por is_active (existen en producción; redundantes con
-- las FULL de arriba pero inocuas — se mantienen por fidelidad al estado real)
create unique index if not exists whatsapp_accounts_phone_number_id_active_unique
  on public.whatsapp_accounts (phone_number_id) where is_active = true;
create unique index if not exists whatsapp_accounts_store_id_active_unique
  on public.whatsapp_accounts (store_id) where is_active = true;

-- ---------------------------------------------------------------------
-- 3) CALENDAR_CONNECTIONS — Google Calendar por tienda
-- ---------------------------------------------------------------------
create table if not exists public.calendar_connections (
  id                  uuid primary key default gen_random_uuid(),
  store_id            uuid not null references public.stores (id) on delete cascade,
  google_calendar_id  text not null,
  mode                text not null default 'shared_service_account',
  created_at          timestamptz not null default now()
);

create unique index if not exists calendar_connections_store_id_key
  on public.calendar_connections (store_id);

-- ---------------------------------------------------------------------
-- 4) CUSTOMERS — cliente final, único por (store_id, phone)
-- ---------------------------------------------------------------------
create table if not exists public.customers (
  id          bigint generated by default as identity primary key,
  store_id    uuid not null references public.stores (id) on delete cascade,
  phone       text not null,
  name        text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- N8: origen del nombre (perfil_whatsapp | cliente | negocio).
-- Los datos de clientes son SIEMPRE por tienda: un mismo teléfono en dos
-- negocios son dos fichas independientes y NO se comparte nada entre ellas.
alter table public.customers add column if not exists name_source text;

create unique index if not exists customers_store_phone_unique
  on public.customers (store_id, phone);
create index if not exists customers_store_id_idx
  on public.customers (store_id);

-- ---------------------------------------------------------------------
-- 5) MESSAGES — log entrante/saliente + idempotencia por WAMID
-- ---------------------------------------------------------------------
create table if not exists public.messages (
  id           bigint generated by default as identity primary key,
  store_id     uuid not null references public.stores (id) on delete cascade,
  customer_id  bigint references public.customers (id) on delete set null,
  phone        text not null,
  content      text not null,
  from_me      boolean not null default false,
  message_id   text,           -- WAMID de Meta (null en salientes actuales)
  raw_payload  jsonb,          -- payload bruto opcional
  created_at   timestamptz not null default now()
);

-- CRÍTICO — idempotencia: un mismo WAMID no se procesa dos veces por tienda
create unique index if not exists messages_store_message_id_unique
  on public.messages (store_id, message_id)
  where message_id is not null;

create index if not exists messages_store_created_at_idx
  on public.messages (store_id, created_at desc);
create index if not exists idx_messages_phone_created
  on public.messages (phone, created_at desc);
create index if not exists messages_customer_created_at_idx
  on public.messages (customer_id, created_at desc);

-- ---------------------------------------------------------------------
-- 6) APPOINTMENTS — citas
-- ---------------------------------------------------------------------
create table if not exists public.appointments (
  id               bigint generated by default as identity primary key,
  store_id         uuid not null references public.stores (id) on delete cascade,
  customer_id      bigint not null references public.customers (id) on delete cascade,
  phone            text,
  start_at         timestamptz not null,
  end_at           timestamptz not null,
  google_event_id  text,
  status           text not null default 'confirmed'
                     check (status in ('pending', 'confirmed', 'cancelled')),
  source           text not null default 'whatsapp'
                     check (source in ('whatsapp', 'admin')),
  notes            text,
  reminder_24h_sent_at    timestamptz,  -- R1: recordatorio 24 h enviado
  reminder_2h_sent_at     timestamptz,  -- R1: recordatorio 2 h enviado
  confirmed_by_client_at  timestamptz,  -- R1: botón [Confirmo] pulsado
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
-- NOTA: el check de status en producción se verificó parcialmente (la lista
-- salía truncada en pantalla). Si el real admite más valores, ajustar aquí.

-- CRÍTICO — anti doble-reserva: solo bloquea entre citas CONFIRMADAS.
-- NUNCA convertir en unique full: impediría rereservar huecos cancelados
-- (bug real corregido en migration_fix_appointments_unique_full.sql).
--
-- B5.1 (migration_equipo.sql): ahora es por PERSONA. El coalesce(resource_id, 0)
-- es imprescindible: sin él, las citas sin persona asignada (NULL) dejarían de
-- chocar entre sí y las tiendas de una sola persona perderían la protección.
create unique index if not exists appointments_store_resource_start_confirmed_unique
  on public.appointments (store_id, coalesce(resource_id, 0), start_at)
  where status = 'confirmed';

create unique index if not exists appointments_store_google_event_id_unique
  on public.appointments (store_id, google_event_id);
create index if not exists appointments_store_start_at_idx
  on public.appointments (store_id, start_at);
create index if not exists appointments_store_status_idx
  on public.appointments (store_id, status);
create index if not exists idx_appointments_customer
  on public.appointments (customer_id);
create index if not exists idx_appointments_start
  on public.appointments (start_at);
create index if not exists appointments_store_id_idx
  on public.appointments (store_id);

-- ---------------------------------------------------------------------
-- 7) CONVERSATION_STATE — estado conversacional persistido (stateless)
-- ---------------------------------------------------------------------
create table if not exists public.conversation_state (
  store_id    uuid not null references public.stores (id) on delete cascade,
  phone       text not null,
  state       jsonb not null default '{}',
  expires_at  timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  primary key (store_id, phone)
);

create index if not exists conversation_state_expires_at_idx
  on public.conversation_state (expires_at);

-- ---------------------------------------------------------------------
-- 8) STORE_BUSINESS_HOURS — horarios por tienda (weekday 0=domingo..6=sábado)
-- ---------------------------------------------------------------------
create table if not exists public.store_business_hours (
  id          uuid primary key default gen_random_uuid(),
  store_id    uuid not null references public.stores (id) on delete cascade,
  weekday     smallint not null check (weekday >= 0 and weekday <= 6),
  open_time   time,
  close_time  time,
  is_closed   boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  -- Coherencia: cerrado sin horas, o abierto con ambas horas
  check (
    (is_closed = true  and open_time is null     and close_time is null)
    or
    (is_closed = false and open_time is not null and close_time is not null)
  )
);

create unique index if not exists store_business_hours_store_id_weekday_key
  on public.store_business_hours (store_id, weekday);

-- ---------------------------------------------------------------------
-- 9) STORE_USERS — vínculo usuario (Supabase Auth) ↔ tienda  [base paso 4]
-- ---------------------------------------------------------------------
create table if not exists public.store_users (
  id          uuid primary key default gen_random_uuid(),
  store_id    uuid not null references public.stores (id) on delete cascade,
  user_id     uuid not null,   -- auth.users.id (sin FK en producción actual)
  role        text not null default 'owner' check (role in ('owner', 'admin')),
  created_at  timestamptz not null default now()
);

create unique index if not exists store_users_store_id_user_id_key
  on public.store_users (store_id, user_id);

